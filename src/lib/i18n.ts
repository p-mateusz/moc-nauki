export function t(key: keyof typeof translations.en, lang: Language = "en"): string {
  const anyTrans = translations as Record<string, Record<string, string>>;
  return (
    anyTrans[lang]?.[key] ||
    anyTrans.en?.[key] ||
    translations.en[key] ||
    key
  );
}

export function getLang(): Language {
  const v = localStorage.getItem("language") as Language | null;
  if (v && LANGUAGE_META[v]) return v;
  return "en";
}